# Define a função Velocidade que calcula a velocidade em 2D a partir de coordenadas X e Y e um vetor de tempos t, retornando a magnitude da velocidade.

def Velocidade(X, Y, t):
    # Inicializar listas para armazenar velocidades e acelerações
    VX = np.zeros(len(X))
    VY = np.zeros(len(Y))
    A = np.zeros(len(X))

    # Calcular a velocidade
    for i in range(len(X) - 1):
        VX[i] = (X[i + 1] - X[i]) / (t[i + 1] - t[i])  # Velocidade em X
        VY[i] = (Y[i + 1] - Y[i]) / (t[i + 1] - t[i])  # Velocidade em Y

    velocidade = np.sqrt(np.power(VX, 2) + np.power(VY, 2))
    angle = np.arctan2(VY, VX)
    # Calcular a aceleração
    for i in range(len(VX) - 1):
        A[i] =  (velocidade[i + 1] - velocidade[i]) / (t[i + 1] - t[i])  # Aceleração em X

    return velocidade, A, angle

