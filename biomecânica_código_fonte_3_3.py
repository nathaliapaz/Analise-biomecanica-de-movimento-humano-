def CalculaTorque(massa_segmento, comprimento_segmento, raio_giro, aceleracao_angular, angulo_articular, massa_corpo=0, distancia_centro_massa_corpo=0):
    """
    Calcula o torque em uma articulação baseado em componentes gravitacionais e inerciais.

    Parâmetros:
    - massa_segmento (float): Massa do segmento em kg (ex.: braço ou antebraço).
    - comprimento_segmento (float): Comprimento do segmento em metros.
    - raio_giro (float): Raio de giro do segmento (proporção do comprimento que define a distribuição de massa).
    - aceleracao_angular (float): Aceleração angular do segmento em rad/s².
    - angulo_articular (float): Ângulo da articulação (em radianos), usado para calcular forças gravitacionais.
    - massa_corpo (float): Massa adicional do corpo em kg (para considerar o peso do corpo suspenso). Default: 0.
    - distancia_centro_massa_corpo (float): Distância do centro de massa do corpo até a articulação, em metros. Default: 0.

    Retorno:
    - torque (float): Torque total na articulação, em N·m.
    """
    # Constante da gravidade
    g = 9.81  # m/s²

    # Momento de inércia do segmento
    momento_inercia = massa_segmento * (raio_giro * comprimento_segmento) ** 2

    # Componente inercial (resistência ao movimento rotacional)
    torque_inercial = momento_inercia * aceleracao_angular

    # Componente gravitacional do segmento
    forca_gravitacional_segmento = massa_segmento * g
    torque_gravitacional_segmento = forca_gravitacional_segmento * (comprimento_segmento / 2) * abs(math.sin(angulo_articular))

    # Componente gravitacional do corpo (se aplicável)
    torque_gravitacional_corpo = massa_corpo * g * distancia_centro_massa_corpo * abs(math.sin(angulo_articular))

    # Torque total
    torque_total = torque_inercial + torque_gravitacional_segmento + torque_gravitacional_corpo

    return torque_total

