def VelocidadeM(X, t):
    # Inicializar listas para armazenar velocidades e acelerações
    VM = np.zeros(len(X))
    A = np.zeros(len(X))

    # Calcular a velocidade
    for i in range(len(X) - 1):
        VM[i] = (X[i + 1] - X[i]) / (t[i + 1] - t[i])  # Velocidade em X

    # Calcular a aceleração
    for i in range(len(VM) - 1):
        A[i] =  (VM[i + 1] - VM[i]) / (t[i + 1] - t[i])  # Aceleração em X

    return VM, A

