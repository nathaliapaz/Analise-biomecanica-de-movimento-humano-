# Função para calcular o vetor unitário da direção da linha
def direction_vector(x1, y1, x2, y2):
    dx = x2 - x1
    dy = y2 - y1
    magnitude = (dx**2 + dy**2)**0.5
    return dx / magnitude, dy / magnitude  # Retorna o vetor unitário

